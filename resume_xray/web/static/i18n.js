const list = (items, lang) => {
  const quoted = items.map((x) => `“${x}”`);
  if (quoted.length < 2) return quoted.join("");
  const and = lang === "tr" ? " ve " : " and ";
  return quoted.slice(0, -1).join(", ") + and + quoted[quoted.length - 1];
};

